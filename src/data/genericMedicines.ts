export function lookupGenericAlternative(brandOrSaltName: string): GenericDrugInfo | null {
  const query = brandOrSaltName.toLowerCase().trim();
  if (!query) return null;

  // Direct brand match
  for (const item of GENERIC_MEDICINES_DB) {
    if (item.brandName.toLowerCase().includes(query) || query.includes(item.brandName.toLowerCase().split(' ')[0])) {
      return item;
    }
  }

  // Salt match
  for (const item of GENERIC_MEDICINES_DB) {
    const saltWords = item.genericSalt.toLowerCase().split(/[ +()0-9mgmcg]+/);
    for (const word of saltWords) {
      if (word.length > 3 && query.includes(word)) {
        return item;
      }
    }
  }

  return null;
}
